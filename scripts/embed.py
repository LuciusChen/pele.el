"""Embed the pinned, unmodified Pele bundle and its host adapter."""
import pathlib
import sys

destination, *sources = map(pathlib.Path, sys.argv[1:])
with destination.open("w") as output:
    output.write("/* Generated by scripts/embed.py. */\n")
    for name, path in zip(("pele_bundle", "pele_bridge"), sources, strict=True):
        data = path.read_bytes()
        output.write(f"static const unsigned char {name}[] = {{\n")
        for index in range(0, len(data), 24):
            output.write(",".join(str(byte) for byte in data[index:index + 24]) + ",\n")
        output.write(f"0\n}};\nstatic const size_t {name}_len = {len(data)};\n")
